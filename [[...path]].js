"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { neon } = require("@neondatabase/serverless");
const { normalizeCustomerIdentifier, validateCustomerRegistration, validateProduct } = require("../lib/validation");

const ROOT = path.join(__dirname, "..");
const ORDER_STATUSES = [
  "Awaiting WhatsApp confirmation",
  "Confirmed",
  "Packed",
  "Shipped",
  "Delivered",
  "Cancelled"
];
const SESSION_TTL_MS = 8 * 60 * 60 * 1000;
const CUSTOMER_SESSION_TTL_MS = 30 * 24 * 60 * 60 * 1000;
const LOGIN_WINDOW_MS = 15 * 60 * 1000;
const MAX_LOGIN_ATTEMPTS = 8;
let sql;
let databaseReady;

function database() {
  if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is not configured.");
  if (!sql) sql = neon(process.env.DATABASE_URL);
  return sql;
}

async function initializeDatabase() {
  if (!databaseReady) {
    databaseReady = (async () => {
      const query = database();
      await query`CREATE TABLE IF NOT EXISTS products (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data jsonb NOT NULL
      )`;
      await query`CREATE TABLE IF NOT EXISTS customers (
        id uuid PRIMARY KEY,
        identifier text NOT NULL UNIQUE,
        data jsonb NOT NULL
      )`;
      await query`CREATE TABLE IF NOT EXISTS orders (
        id uuid PRIMARY KEY,
        created_at timestamptz NOT NULL,
        status text NOT NULL,
        data jsonb NOT NULL
      )`;
      await query`CREATE INDEX IF NOT EXISTS orders_created_at_idx ON orders (created_at DESC)`;
      await query`CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status)`;
      await query`CREATE TABLE IF NOT EXISTS newsletter_subscribers (
        email text PRIMARY KEY,
        subscribed_at timestamptz NOT NULL
      )`;
      await query`CREATE TABLE IF NOT EXISTS sessions (
        token_hash text PRIMARY KEY,
        kind text NOT NULL CHECK (kind IN ('admin', 'customer')),
        customer_id uuid REFERENCES customers (id) ON DELETE CASCADE,
        expires_at timestamptz NOT NULL
      )`;
      await query`CREATE INDEX IF NOT EXISTS sessions_expires_at_idx ON sessions (expires_at)`;
      await query`CREATE TABLE IF NOT EXISTS rate_limits (
        scope text NOT NULL,
        client_key text NOT NULL,
        count integer NOT NULL,
        reset_at timestamptz NOT NULL,
        PRIMARY KEY (scope, client_key)
      )`;

      const productCount = await query`SELECT count(*)::integer AS count FROM products`;
      if (productCount[0].count === 0) {
        const initialProducts = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "products.json"), "utf8"));
        for (const product of initialProducts) {
          await query`INSERT INTO products (id, data)
            VALUES (${product.id}, ${JSON.stringify(product)}::jsonb)
            ON CONFLICT (id) DO NOTHING`;
        }
      }
      await query`SELECT setval(
        pg_get_serial_sequence('products', 'id'),
        GREATEST(COALESCE((SELECT MAX(id) FROM products), 0), 1),
        EXISTS (SELECT 1 FROM products)
      )`;
    })().catch(error => {
      databaseReady = null;
      throw error;
    });
  }
  await databaseReady;
}

function send(res, status, body, contentType = "text/plain; charset=utf-8", headers = {}) {
  res.writeHead(status, {
    "Content-Type": contentType,
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "same-origin",
    "Cache-Control": "no-store",
    ...headers
  });
  res.end(body);
}

function sendJson(res, status, payload, headers = {}) {
  send(res, status, JSON.stringify(payload), "application/json; charset=utf-8", headers);
}

async function readJson(req) {
  if (req.body !== undefined) {
    if (typeof req.body === "string" || Buffer.isBuffer(req.body)) {
      try {
        return JSON.parse(req.body.toString());
      } catch {
        throw new Error("Invalid JSON.");
      }
    }
    return req.body;
  }

  return new Promise((resolve, reject) => {
    let body = "";
    let tooLarge = false;
    req.setEncoding("utf8");
    req.on("data", chunk => {
      if (tooLarge) return;
      body += chunk;
      if (Buffer.byteLength(body) > 8192) {
        tooLarge = true;
        body = "";
      }
    });
    req.on("end", () => {
      if (tooLarge) {
        reject(new Error("Request body too large."));
        return;
      }
      try {
        resolve(JSON.parse(body));
      } catch {
        reject(new Error("Invalid JSON."));
      }
    });
    req.on("error", reject);
  });
}

function safeEqual(received, expected) {
  const receivedBytes = Buffer.from(received);
  const expectedBytes = Buffer.from(expected);
  return receivedBytes.length === expectedBytes.length
    && crypto.timingSafeEqual(receivedBytes, expectedBytes);
}

function cookieToken(req, name) {
  const cookie = (req.headers.cookie || "")
    .split(";")
    .map(part => part.trim())
    .find(part => part.startsWith(`${name}=`));
  return cookie ? cookie.slice(name.length + 1) : "";
}

function hashToken(token) {
  return crypto.createHash("sha256").update(token).digest("hex");
}

async function getSession(req, kind) {
  const token = cookieToken(req, kind === "admin" ? "zohd_admin" : "zohd_customer");
  if (!/^[a-f0-9]{64}$/i.test(token)) return null;
  const rows = await database()`SELECT customer_id FROM sessions
    WHERE token_hash = ${hashToken(token)} AND kind = ${kind} AND expires_at > now()`;
  return rows.length ? { token, customerId: rows[0].customer_id } : null;
}

async function createSession(res, kind, customerId = null) {
  const token = crypto.randomBytes(32).toString("hex");
  const expiresAt = new Date(Date.now() + (kind === "admin" ? SESSION_TTL_MS : CUSTOMER_SESSION_TTL_MS));
  await database()`INSERT INTO sessions (token_hash, kind, customer_id, expires_at)
    VALUES (${hashToken(token)}, ${kind}, ${customerId}, ${expiresAt})`;
  const cookieName = kind === "admin" ? "zohd_admin" : "zohd_customer";
  const cookieParts = [
    `${cookieName}=${token}`,
    "Path=/",
    "HttpOnly",
    "SameSite=Strict",
    `Max-Age=${Math.floor((expiresAt.getTime() - Date.now()) / 1000)}`
  ];
  if (process.env.NODE_ENV === "production") cookieParts.push("Secure");
  return cookieParts.join("; ");
}

async function clearSession(req, kind) {
  const token = cookieToken(req, kind === "admin" ? "zohd_admin" : "zohd_customer");
  if (token && /^[a-f0-9]{64}$/i.test(token)) {
    await database()`DELETE FROM sessions WHERE token_hash = ${hashToken(token)} AND kind = ${kind}`;
  }
  const cookieName = kind === "admin" ? "zohd_admin" : "zohd_customer";
  return `${cookieName}=; Path=/; HttpOnly; SameSite=Strict; Max-Age=0${process.env.NODE_ENV === "production" ? "; Secure" : ""}`;
}

function publicCustomer(customer) {
  return {
    id: customer.id,
    name: customer.name,
    identifier: customer.identifier,
    address: customer.address,
    location: customer.location,
    createdAt: customer.createdAt
  };
}

function hashCustomerPassword(password, salt = crypto.randomBytes(16)) {
  return new Promise((resolve, reject) => {
    crypto.scrypt(password, salt, 64, (error, derivedKey) => {
      if (error) {
        reject(error);
        return;
      }
      resolve({ salt: salt.toString("hex"), passwordHash: derivedKey.toString("hex") });
    });
  });
}

function clientKey(req) {
  const forwarded = req.headers["x-forwarded-for"];
  const address = typeof forwarded === "string"
    ? forwarded.split(",")[0].trim()
    : req.socket?.remoteAddress || "unknown";
  return crypto.createHash("sha256").update(address).digest("hex");
}

async function rateLimit(req, res, scope, message) {
  const rows = await database()`INSERT INTO rate_limits (scope, client_key, count, reset_at)
    VALUES (${scope}, ${clientKey(req)}, 1, now() + interval '15 minutes')
    ON CONFLICT (scope, client_key) DO UPDATE
    SET count = CASE WHEN rate_limits.reset_at <= now() THEN 1 ELSE rate_limits.count + 1 END,
        reset_at = CASE WHEN rate_limits.reset_at <= now()
          THEN now() + interval '15 minutes' ELSE rate_limits.reset_at END
    RETURNING count, reset_at`;
  if (rows[0].count <= MAX_LOGIN_ATTEMPTS) return true;
  const retrySeconds = Math.max(1, Math.ceil((new Date(rows[0].reset_at).getTime() - Date.now()) / 1000));
  sendJson(res, 429, { error: message }, { "Retry-After": String(retrySeconds) });
  return false;
}

async function clearRateLimit(req, scope) {
  await database()`DELETE FROM rate_limits WHERE scope = ${scope} AND client_key = ${clientKey(req)}`;
}

async function getProducts() {
  const rows = await database()`SELECT data FROM products ORDER BY id`;
  return rows.map(row => row.data);
}

async function getCustomerByIdentifier(identifier) {
  const rows = await database()`SELECT data FROM customers WHERE identifier = ${identifier}`;
  return rows.length ? rows[0].data : null;
}

function serveAdminFile(res, filename) {
  const filePath = path.join(ROOT, "private", filename);
  fs.readFile(filePath, (error, data) => {
    if (error) {
      console.error("Failed to read admin page:", error);
      send(res, 500, "Unable to read requested page.");
      return;
    }
    send(res, 200, data, "text/html; charset=utf-8");
  });
}

function cookieForEmptySession(kind) {
  const name = kind === "admin" ? "zohd_admin" : "zohd_customer";
  return `${name}=; Path=/; HttpOnly; SameSite=Strict; Max-Age=0${process.env.NODE_ENV === "production" ? "; Secure" : ""}`;
}

async function handle(req, res) {
  let pathname;
  try {
    pathname = new URL(req.url, "https://vercel.local").pathname;
  } catch {
    send(res, 400, "Bad request.");
    return;
  }

  try {
    await initializeDatabase();

    if (req.method === "GET" && pathname === "/api/admin") {
      if (await getSession(req, "admin")) {
        res.writeHead(303, { Location: "/admin/dashboard", "Cache-Control": "no-store" });
        res.end();
      } else {
        serveAdminFile(res, "admin-login.html");
      }
      return;
    }

    if (req.method === "GET" && pathname === "/api/admin/dashboard") {
      if (!(await getSession(req, "admin"))) {
        res.writeHead(303, { Location: "/admin", "Cache-Control": "no-store" });
        res.end();
        return;
      }
      serveAdminFile(res, "admin.html");
      return;
    }

    if (req.method === "POST" && pathname === "/api/admin/login") {
      if (!(await rateLimit(req, res, "admin-login", "Too many login attempts."))) return;
      if (!process.env.ADMIN_ID || !process.env.ADMIN_PASSWORD) {
        sendJson(res, 503, { error: "Admin login is not configured on the server." });
        return;
      }
      let credentials;
      try {
        credentials = await readJson(req);
      } catch (error) {
        sendJson(res, 400, { error: error.message });
        return;
      }
      const adminId = process.env.ADMIN_ID || "";
      const adminPassword = process.env.ADMIN_PASSWORD || "";
      const hasValidShape = credentials && typeof credentials.adminId === "string" && typeof credentials.password === "string";
      const isValid = adminId && adminPassword && hasValidShape
        && safeEqual(credentials.adminId, adminId)
        && safeEqual(credentials.password, adminPassword);
      if (!isValid) {
        sendJson(res, 401, { error: "Invalid credentials." });
        return;
      }
      await clearRateLimit(req, "admin-login");
      const cookie = await createSession(res, "admin");
      send(res, 204, "", "text/plain; charset=utf-8", { "Set-Cookie": cookie });
      return;
    }

    if (req.method === "POST" && pathname === "/api/admin/logout") {
      const cookie = await clearSession(req, "admin");
      send(res, 204, "", "text/plain; charset=utf-8", { "Set-Cookie": cookie });
      return;
    }

    if (req.method === "POST" && pathname === "/api/newsletter/subscribe") {
      if (!(await rateLimit(req, res, "newsletter", "Too many subscription attempts. Please try again later."))) return;
      let input;
      try {
        input = await readJson(req);
      } catch (error) {
        sendJson(res, 400, { error: error.message });
        return;
      }
      const email = input && typeof input.email === "string" ? input.email.trim().toLowerCase() : "";
      if (email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
        sendJson(res, 400, { error: "Enter a valid email address." });
        return;
      }
      if (!input || input.consent !== true) {
        sendJson(res, 400, { error: "Please confirm you agree to receive product updates." });
        return;
      }
      const inserted = await database()`INSERT INTO newsletter_subscribers (email, subscribed_at)
        VALUES (${email}, now()) ON CONFLICT (email) DO NOTHING RETURNING email`;
      await clearRateLimit(req, "newsletter");
      sendJson(res, inserted.length ? 201 : 200, { message: "Subscription saved." });
      return;
    }

    if (req.method === "POST" && pathname === "/api/customer/register") {
      if (!(await rateLimit(req, res, "customer-auth", "Too many account attempts. Please try again later."))) return;
      let input;
      try {
        input = await readJson(req);
      } catch (error) {
        sendJson(res, 400, { error: error.message });
        return;
      }
      const validation = validateCustomerRegistration(input);
      if (validation.error) {
        sendJson(res, 400, { error: validation.error });
        return;
      }
      const credentials = await hashCustomerPassword(validation.customer.password);
      const customer = {
        id: crypto.randomUUID(),
        name: validation.customer.name,
        identifier: validation.customer.identifier,
        address: validation.customer.address,
        location: validation.customer.location,
        salt: credentials.salt,
        passwordHash: credentials.passwordHash,
        createdAt: new Date().toISOString()
      };
      try {
        await database()`INSERT INTO customers (id, identifier, data)
          VALUES (${customer.id}, ${customer.identifier}, ${JSON.stringify(customer)}::jsonb)`;
      } catch (error) {
        if (error.code === "23505") {
          sendJson(res, 409, { error: "An account with that email or phone number already exists." });
          return;
        }
        throw error;
      }
      await clearRateLimit(req, "customer-auth");
      const cookie = await createSession(res, "customer", customer.id);
      sendJson(res, 201, { customer: publicCustomer(customer) }, { "Set-Cookie": cookie });
      return;
    }

    if (req.method === "POST" && pathname === "/api/customer/login") {
      if (!(await rateLimit(req, res, "customer-auth", "Too many account attempts. Please try again later."))) return;
      let input;
      try {
        input = await readJson(req);
      } catch (error) {
        sendJson(res, 400, { error: error.message });
        return;
      }
      const identifier = normalizeCustomerIdentifier(input && typeof input.identifier === "string" ? input.identifier : "");
      const password = input && typeof input.password === "string" ? input.password : "";
      const customer = await getCustomerByIdentifier(identifier);
      let passwordMatches = false;
      if (customer && password.length <= 1024) {
        const derived = await hashCustomerPassword(password, Buffer.from(customer.salt, "hex"));
        const expected = Buffer.from(customer.passwordHash, "hex");
        const received = Buffer.from(derived.passwordHash, "hex");
        passwordMatches = expected.length === received.length && crypto.timingSafeEqual(expected, received);
      }
      if (!customer || !passwordMatches) {
        sendJson(res, 401, { error: "Email/phone or password is incorrect." });
        return;
      }
      await clearRateLimit(req, "customer-auth");
      const cookie = await createSession(res, "customer", customer.id);
      sendJson(res, 200, { customer: publicCustomer(customer) }, { "Set-Cookie": cookie });
      return;
    }

    if (req.method === "GET" && pathname === "/api/customer/me") {
      const session = await getSession(req, "customer");
      if (!session) {
        sendJson(res, 401, { error: "Customer authentication required." });
        return;
      }
      const rows = await database()`SELECT data FROM customers WHERE id = ${session.customerId}`;
      if (!rows.length) {
        sendJson(res, 401, { error: "Customer authentication required." });
        return;
      }
      sendJson(res, 200, { customer: publicCustomer(rows[0].data) });
      return;
    }

    if (req.method === "POST" && pathname === "/api/customer/logout") {
      const cookie = await clearSession(req, "customer");
      send(res, 204, "", "text/plain; charset=utf-8", { "Set-Cookie": cookie });
      return;
    }

    if (req.method === "POST" && pathname === "/api/orders") {
      const session = await getSession(req, "customer");
      if (!session) {
        sendJson(res, 401, { error: "Sign in to your customer account before placing an order." });
        return;
      }
      const customerRows = await database()`SELECT data FROM customers WHERE id = ${session.customerId}`;
      if (!customerRows.length) {
        sendJson(res, 401, { error: "Sign in to your customer account before placing an order." });
        return;
      }
      let input;
      try {
        input = await readJson(req);
      } catch (error) {
        sendJson(res, 400, { error: error.message });
        return;
      }
      if (!input || typeof input !== "object" || Array.isArray(input)
        || !Array.isArray(input.items) || input.items.length === 0 || input.items.length > 20) {
        sendJson(res, 400, { error: "An order must contain between 1 and 20 cart items." });
        return;
      }
      const products = await getProducts();
      const orderItems = [];
      const requestedQuantities = new Map();
      for (const item of input.items) {
        if (!item || typeof item !== "object" || !Number.isInteger(item.productId)
          || typeof item.variant !== "string" || !Number.isInteger(item.quantity)
          || item.quantity < 1 || item.quantity > 99) {
          sendJson(res, 400, { error: "Each order item needs a valid product, variant, and quantity from 1 to 99." });
          return;
        }
        const product = products.find(entry => entry.id === item.productId);
        if (!product || !product.variants.includes(item.variant)) {
          sendJson(res, 400, { error: "A product or variant in your bag is no longer available. Refresh the catalog and try again." });
          return;
        }
        if (product.stock !== "In Stock") {
          sendJson(res, 409, { error: `${product.name} is currently out of stock.` });
          return;
        }
        requestedQuantities.set(product.id, (requestedQuantities.get(product.id) || 0) + item.quantity);
        const lineTotal = Number((product.price * item.quantity).toFixed(2));
        if (!Number.isFinite(lineTotal) || lineTotal > 10000000) {
          sendJson(res, 400, { error: "The order total is outside the supported range." });
          return;
        }
        orderItems.push({
          productId: product.id,
          name: product.name,
          variant: item.variant,
          unitPrice: product.price,
          quantity: item.quantity,
          lineTotal
        });
      }
      for (const [productId, requestedQuantity] of requestedQuantities) {
        const product = products.find(entry => entry.id === productId);
        if (Number.isInteger(product.quantity) && requestedQuantity > product.quantity) {
          sendJson(res, 409, { error: `Only ${product.quantity} ${product.name} item(s) are currently available.` });
          return;
        }
      }
      const subtotal = Number(orderItems.reduce((sum, item) => sum + item.lineTotal, 0).toFixed(2));
      if (!Number.isFinite(subtotal) || subtotal > 10000000) {
        sendJson(res, 400, { error: "The order total is outside the supported range." });
        return;
      }
      const now = new Date().toISOString();
      const order = {
        id: crypto.randomUUID(),
        orderNumber: `ZOHD-${Date.now().toString(36).toUpperCase()}-${crypto.randomBytes(3).toString("hex").toUpperCase()}`,
        customer: {
          id: customerRows[0].data.id,
          name: customerRows[0].data.name,
          identifier: customerRows[0].data.identifier,
          address: customerRows[0].data.address,
          location: customerRows[0].data.location
        },
        items: orderItems,
        subtotal,
        status: ORDER_STATUSES[0],
        createdAt: now,
        updatedAt: now
      };
      await database()`INSERT INTO orders (id, created_at, status, data)
        VALUES (${order.id}, ${now}, ${order.status}, ${JSON.stringify(order)}::jsonb)`;
      sendJson(res, 201, { order });
      return;
    }

    if (pathname === "/api/admin/orders") {
      if (!(await getSession(req, "admin"))) {
        sendJson(res, 401, { error: "Admin authentication required." });
        return;
      }
      if (req.method === "GET") {
        const rows = await database()`SELECT data FROM orders ORDER BY created_at DESC`;
        sendJson(res, 200, rows.map(row => row.data));
      } else {
        sendJson(res, 405, { error: "Method not allowed." });
      }
      return;
    }

    const orderStatusRoute = pathname.match(/^\/api\/admin\/orders\/([0-9a-f-]+)\/status$/i);
    if (orderStatusRoute) {
      if (!(await getSession(req, "admin"))) {
        sendJson(res, 401, { error: "Admin authentication required." });
        return;
      }
      if (req.method !== "PUT") {
        sendJson(res, 405, { error: "Method not allowed." });
        return;
      }
      let input;
      try {
        input = await readJson(req);
      } catch (error) {
        sendJson(res, 400, { error: error.message });
        return;
      }
      if (!input || typeof input.status !== "string" || !ORDER_STATUSES.includes(input.status)) {
        sendJson(res, 400, { error: "Choose a valid order status." });
        return;
      }
      const rows = await database()`SELECT data FROM orders WHERE id = ${orderStatusRoute[1]}`;
      if (!rows.length) {
        sendJson(res, 404, { error: "Order not found." });
        return;
      }
      const order = { ...rows[0].data, status: input.status, updatedAt: new Date().toISOString() };
      await database()`UPDATE orders SET status = ${order.status}, data = ${JSON.stringify(order)}::jsonb
        WHERE id = ${order.id}`;
      sendJson(res, 200, order);
      return;
    }

    if (req.method === "GET" && pathname === "/api/products") {
      const products = await getProducts();
      sendJson(res, 200, products.map(({ quantity, ...product }) => product));
      return;
    }

    if (pathname === "/api/admin/products") {
      if (!(await getSession(req, "admin"))) {
        sendJson(res, 401, { error: "Admin authentication required." });
        return;
      }
      if (req.method === "GET") {
        sendJson(res, 200, await getProducts());
        return;
      }
      if (req.method === "POST") {
        let input;
        try {
          input = await readJson(req);
        } catch (error) {
          sendJson(res, 400, { error: error.message });
          return;
        }
        const validation = validateProduct(input);
        if (validation.error) {
          sendJson(res, 400, { error: validation.error });
          return;
        }
        const rows = await database()`INSERT INTO products (data)
          VALUES (jsonb_set(${JSON.stringify(validation.product)}::jsonb, '{id}',
            to_jsonb(nextval(pg_get_serial_sequence('products', 'id'))::integer)))
          RETURNING data`;
        sendJson(res, 201, rows[0].data);
        return;
      }
      sendJson(res, 405, { error: "Method not allowed." });
      return;
    }

    const productRoute = pathname.match(/^\/api\/admin\/products\/(\d+)$/);
    if (productRoute) {
      if (!(await getSession(req, "admin"))) {
        sendJson(res, 401, { error: "Admin authentication required." });
        return;
      }
      const productId = Number(productRoute[1]);
      const query = database();
      const existing = await query`SELECT data FROM products WHERE id = ${productId}`;
      if (!existing.length) {
        sendJson(res, 404, { error: "Product not found." });
        return;
      }
      if (req.method === "PUT") {
        let input;
        try {
          input = await readJson(req);
        } catch (error) {
          sendJson(res, 400, { error: error.message });
          return;
        }
        const validation = validateProduct(input);
        if (validation.error) {
          sendJson(res, 400, { error: validation.error });
          return;
        }
        const product = { id: productId, ...validation.product };
        await query`UPDATE products SET data = ${JSON.stringify(product)}::jsonb WHERE id = ${productId}`;
        sendJson(res, 200, product);
        return;
      }
      if (req.method === "DELETE") {
        await query`DELETE FROM products WHERE id = ${productId}`;
        send(res, 204, "");
        return;
      }
      sendJson(res, 405, { error: "Method not allowed." });
      return;
    }

    send(res, 404, "Not found.");
  } catch (error) {
    console.error("Vercel API request failed:", error);
    if (error.message === "DATABASE_URL is not configured.") {
      if (!res.headersSent) {
        sendJson(res, 503, { error: "The store database is not connected. Add DATABASE_URL in the Vercel project environment variables." });
      }
      return;
    }
    if (!res.headersSent) sendJson(res, 500, { error: "The server could not complete this request. Please try again." });
  }
}

